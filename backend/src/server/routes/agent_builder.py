def _available_tool_context() -> str:
    rows: list[str] = []
    for server in _mcp_servers.values():
        if server.status != "installed" or not server.enabled:
            continue
        for tool in server.tools:
            rows.append(f"- id={tool.id}; name={tool.name}; description={tool.description}")
    return "\n".join(rows[:80])


def _available_skill_context() -> str:
    rows: list[str] = []
    for skill in _skills.values():
        if not skill.enabled:
            continue
        rows.append(
            f"- id={skill.id}; name={skill.name}; category={skill.category}; "
            f"description={skill.description}; trigger={skill.trigger}"
        )
    return "\n".join(rows[:80])


def _resolve_tools(names: list[str]) -> tuple[list[BuilderRecommendedItem], list[str]]:
    matched: list[BuilderRecommendedItem] = []
    missing: list[str] = []
    tools = [
        tool
        for server in _mcp_servers.values()
        if server.status == "installed" and server.enabled
        for tool in server.tools
    ]
    for name in names:
        found = _best_match(name, [(tool.id, tool.name, tool.description) for tool in tools])
        if found:
            matched.append(BuilderRecommendedItem(
                id=found[0],
                name=found[1],
                reason=f"匹配需求能力: {name}",
                matched=True,
            ))
        else:
            missing.append(name)
    return matched, missing


def _resolve_skills(names: list[str]) -> tuple[list[BuilderRecommendedItem], list[str]]:
    matched: list[BuilderRecommendedItem] = []
    missing: list[str] = []
    skills = [skill for skill in _skills.values() if skill.enabled]
    for name in names:
        found = _best_match(
            name,
            [
                (skill.id, skill.name, " ".join([skill.description, skill.trigger, " ".join(skill.tags)]))
                for skill in skills
            ],
        )
        if found:
            matched.append(BuilderRecommendedItem(
                id=found[0],
                name=found[1],
                reason=f"匹配需求能力: {name}",
                matched=True,
            ))
        else:
            missing.append(name)
    return matched, missing


def _best_match(query: str, candidates: list[tuple[str, str, str]]) -> tuple[str, str, str] | None:
    needle = query.strip().lower()
    if not needle:
        return None
    for candidate in candidates:
        haystack = " ".join(candidate).lower()
        if needle in haystack or any(part and part in haystack for part in re.split(r"[\s,_/-]+", needle)):
            return candidate
    return None


def _guess_tool_names(requirement: str) -> list[str]:
    text = requirement.lower()
    guesses: list[str] = []
    if any(word in text for word in ["搜索", "互联网", "web", "网页", "资料"]):
        guesses.append("web search")
    if any(word in text for word in ["代码", "项目", "文件", "实现", "修复"]):
        guesses.extend(["filesystem", "code search"])
    if any(word in text for word in ["数据库", "sql", "sqlite"]):
        guesses.append("database")
    return _unique_nonempty(guesses)


def _guess_skill_names(requirement: str) -> list[str]:
    text = requirement.lower()
    guesses: list[str] = []
    if any(word in text for word in ["需求", "prd", "产品"]):
        guesses.append("prd writing")
    if any(word in text for word in ["架构", "方案", "设计"]):
        guesses.append("architecture design")
    if any(word in text for word in ["测试", "验证", "review", "评审"]):
        guesses.append("test review")
    return _unique_nonempty(guesses)


def _parse_json_object(text: str) -> dict:
    stripped = text.strip()
    if stripped.startswith("```"):
        stripped = re.sub(r"^```(?:json)?", "", stripped).strip()
        stripped = re.sub(r"```$", "", stripped).strip()
    try:
        parsed = json.loads(stripped)
    except json.JSONDecodeError:
        match = re.search(r"\{.*\}", stripped, re.S)
        if not match:
            raise ValueError("模型没有返回 JSON 对象")
        parsed = json.loads(match.group(0))
    if not isinstance(parsed, dict):
        raise ValueError("模型返回 JSON 顶层必须是对象")
    return parsed


def _as_string_list(value: object) -> list[str]:
    if not isinstance(value, list):
        return []
    return [str(item).strip() for item in value if str(item).strip()]


def _unique_nonempty(items: list[str]) -> list[str]:
    seen: set[str] = set()
    result: list[str] = []
    for item in items:
        value = str(item).strip()
        key = value.lower()
        if value and key not in seen:
            seen.add(key)
            result.append(value)
    return result


def _make_title(requirement: str, fallback: str) -> str:
    compact = " ".join(requirement.strip().split())
    if not compact:
        return fallback
    title = compact[:24]
    if len(compact) <= 24 and not title.endswith(("团队", "Agent", "agent")):
        title += "团队"
    return title


def _default_agent_prompt(name: str, description: str) -> str:
    return "\n".join([
        f"You are {name}.",
        description or "Work carefully according to your assigned responsibility.",
        "Use bound MCP tools and Skills when they are relevant.",
        "When working inside a Team, complete your own ReAct loop and return focused output for the leader.",
    ])
