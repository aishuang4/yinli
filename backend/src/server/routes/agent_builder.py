"""Agent 智能创建路由。

根据自然语言需求生成可审核的 Agent 草案，匹配现有 MCP 工具和 Skills，
确认后只创建独立 Agent，不创建持久 Team。
"""

import json
import re
import uuid

from fastapi import APIRouter
from pydantic import BaseModel, Field

from agentscope.message import UserMsg
from agentscope.permission import PermissionMode

from src.agents.factory import get_or_create_agent
from src.config.runtime_settings import MODEL_PROVIDERS, get_effective_model_settings
from src.server.routes.agents import AgentCreate, AgentResponse, Guardrails, ModelConfig, create_agent
from src.server.routes.mcp import _mcp_servers
from src.server.routes.skills import _skills

router = APIRouter()

class BuilderPlanRequest(BaseModel):
    """Generate a draft from a user requirement."""

    requirement: str = Field(..., min_length=4, max_length=4000)
    preferred_model: str = Field(default="", alias="preferredModel")

    model_config = {"populate_by_name": True, "extra": "forbid"}


class BuilderRecommendedItem(BaseModel):
    """Tool/Skill recommendation resolved against local resources."""

    id: str = ""
    name: str
    reason: str = ""
    matched: bool = False


class BuilderAgentDraft(BaseModel):
    """One Agent draft generated by the builder."""

    temp_id: str = Field(default_factory=lambda: f"draft-{uuid.uuid4().hex}", alias="tempId")
    name: str
    description: str = ""
    system_prompt: str = Field(default="", alias="systemPrompt")
    model_config_data: ModelConfig = Field(default_factory=ModelConfig, alias="modelConfig")
    mcp_tools: list[str] = Field(default_factory=list, alias="mcpTools")
    skills: list[str] = Field(default_factory=list)
    tags: list[str] = Field(default_factory=list)
    recommended_tools: list[BuilderRecommendedItem] = Field(default_factory=list, alias="recommendedTools")
    recommended_skills: list[BuilderRecommendedItem] = Field(default_factory=list, alias="recommendedSkills")
    missing_tools: list[str] = Field(default_factory=list, alias="missingTools")
    missing_skills: list[str] = Field(default_factory=list, alias="missingSkills")

    model_config = {"populate_by_name": True, "extra": "forbid"}


class BuilderPlanResponse(BaseModel):
    """Full reviewable builder draft."""

    id: str = Field(default_factory=lambda: uuid.uuid4().hex)
    requirement: str
    agents: list[BuilderAgentDraft] = Field(default_factory=list)
    warnings: list[str] = Field(default_factory=list)

    model_config = {"extra": "forbid"}


class BuilderApplyRequest(BaseModel):
    """Apply a confirmed builder draft."""

    plan: BuilderPlanResponse

    model_config = {"extra": "forbid"}


class BuilderApplyResponse(BaseModel):
    """Created persistent records."""

    created_agents: list[AgentResponse] = Field(alias="createdAgents")
    warnings: list[str] = Field(default_factory=list)

    model_config = {"populate_by_name": True}


@router.post("/plan", response_model=BuilderPlanResponse)
async def plan_agents(data: BuilderPlanRequest) -> BuilderPlanResponse:
    """生成可审核的 Agent 创建草案。"""

    warnings: list[str] = []
    raw_plan: dict | None = None
    runtime_settings = get_effective_model_settings()
    provider = MODEL_PROVIDERS.get(runtime_settings.provider)
    if not provider or not provider.requires_api_key or runtime_settings.api_key:
        try:
            raw_plan = await _generate_plan_with_model(data)
        except Exception as exc:
            warnings.append(f"模型规划失败，已使用本地规则生成草案: {exc}")
    else:
        warnings.append(f"{provider.name} API Key 未配置，已使用本地规则生成草案。")

    if raw_plan is None:
        raw_plan = _heuristic_plan(data)

    plan = _normalize_plan(data, raw_plan)
    plan.warnings = [*warnings, *plan.warnings]
    return plan


@router.post("/apply", response_model=BuilderApplyResponse)
async def apply_agents(data: BuilderApplyRequest) -> BuilderApplyResponse:
    """从确认后的草案创建独立 Agent。"""

    created_agents: list[AgentResponse] = []
    warnings = list(data.plan.warnings)

    for draft in data.plan.agents:
        agent = await create_agent(AgentCreate(
            name=draft.name,
            description=draft.description,
            system_prompt=draft.system_prompt or _default_agent_prompt(draft.name, draft.description),
            modelConfig=draft.model_config_data,
            mcpTools=draft.mcp_tools,
            skills=draft.skills,
            tags=draft.tags,
            guardrails=Guardrails(human_approval=True),
        ))
        created_agents.append(agent)

    return BuilderApplyResponse(
        createdAgents=created_agents,
        warnings=warnings,
    )


async def _generate_plan_with_model(data: BuilderPlanRequest) -> dict:
    """Call a planner Agent and parse its JSON response."""

    available_tools = _available_tool_context()
    available_skills = _available_skill_context()
    system_prompt = "\n".join([
        "You are an Agent configuration planner.",
        "Return only valid JSON. Do not use tools.",
        "Design reviewable Agent drafts from the user requirement.",
        "Use existing MCP tool ids and Skill ids only when they match the role.",
        "If a needed capability is missing, put its natural-language name in missingTools or missingSkills.",
        "JSON schema:",
        "{",
        '  "agents": [',
        '    {"name": "...", "description": "...", "systemPrompt": "...",',
        '     "recommendedTools": ["tool name"], "recommendedSkills": ["skill name"],',
        '     "missingTools": ["..."], "missingSkills": ["..."], "tags": ["..."]}',
        "  ],",
        '  "warnings": ["..."]',
        "}",
    ])
    user_prompt = "\n\n".join([
        f"Requirement:\n{data.requirement}",
        f"Available MCP tools:\n{available_tools or '(none)'}",
        f"Available Skills:\n{available_skills or '(none)'}",
        "Generate one or more standalone Agents. Never create a Team or fixed member list.",
    ])
    runtime_settings = get_effective_model_settings()
    model_name = data.preferred_model or runtime_settings.default_model
    agent = get_or_create_agent(
        agent_id=f"agent-builder:{model_name}",
        name="Agent Builder",
        system_prompt=system_prompt,
        model_name=model_name,
        thinking_enable=False,
        fallback_names=runtime_settings.fallback_models,
        permission_mode=PermissionMode.BYPASS,
    )
    text = ""
    async for event in agent.reply_stream(UserMsg(name="user", content=user_prompt)):
        event_data = event.model_dump(mode="json")
        if event_data.get("type") == "TEXT_BLOCK_DELTA":
            text += str(event_data.get("delta", ""))
    return _parse_json_object(text)


def _normalize_plan(data: BuilderPlanRequest, raw: dict) -> BuilderPlanResponse:
    """Validate model output and resolve local tools/skills."""

    agents_raw = raw.get("agents") if isinstance(raw.get("agents"), list) else []
    warnings = [str(item) for item in raw.get("warnings", []) if str(item).strip()]

    drafts: list[BuilderAgentDraft] = []
    for index, item in enumerate(agents_raw):
        if not isinstance(item, dict):
            continue
        tool_names = _as_string_list(item.get("recommendedTools") or item.get("tools"))
        skill_names = _as_string_list(item.get("recommendedSkills") or item.get("skills"))
        resolved_tools, missing_tools = _resolve_tools(tool_names)
        resolved_skills, missing_skills = _resolve_skills(skill_names)
        missing_tools.extend(_as_string_list(item.get("missingTools")))
        missing_skills.extend(_as_string_list(item.get("missingSkills")))

        name = str(item.get("name") or f"Agent {index + 1}").strip()
        description = str(item.get("description") or "").strip()
        runtime_settings = get_effective_model_settings()
        draft = BuilderAgentDraft(
            name=name[:50],
            description=description[:200],
            systemPrompt=str(item.get("systemPrompt") or item.get("system_prompt") or _default_agent_prompt(name, description)),
            modelConfig=ModelConfig(
                primary=data.preferred_model or runtime_settings.default_model,
                fallback=runtime_settings.fallback_models[:3] or ["deepseek-reasoner"],
                temperature=0.7,
                max_tokens=4096,
            ),
            mcpTools=[item.id for item in resolved_tools if item.id],
            skills=[item.id for item in resolved_skills if item.id],
            tags=_as_string_list(item.get("tags"))[:6],
            recommendedTools=resolved_tools,
            recommendedSkills=resolved_skills,
            missingTools=_unique_nonempty(missing_tools),
            missingSkills=_unique_nonempty(missing_skills),
        )
        drafts.append(draft)

    if not drafts:
        return _normalize_plan(data, _heuristic_plan(data))

    for draft in drafts:
        if draft.missing_tools:
            warnings.append(f"{draft.name} 缺少 MCP 工具: {', '.join(draft.missing_tools)}")
        if draft.missing_skills:
            warnings.append(f"{draft.name} 缺少 Skills: {', '.join(draft.missing_skills)}")

    return BuilderPlanResponse(
        requirement=data.requirement,
        agents=drafts,
        warnings=_unique_nonempty(warnings),
    )


def _heuristic_plan(data: BuilderPlanRequest) -> dict:
    """Fallback draft when model planning is unavailable."""

    requirement = data.requirement
    return {
        "agents": [
            {
                "name": _make_title(requirement, "需求处理 Agent"),
                "description": "根据用户需求完成分析、执行和总结。",
                "systemPrompt": _default_agent_prompt("需求处理 Agent", requirement),
                "recommendedTools": _guess_tool_names(requirement),
                "recommendedSkills": _guess_skill_names(requirement),
                "missingTools": [],
                "missingSkills": [],
                "tags": ["auto-built"],
            },
        ],
        "warnings": ["模型规划不可用，已生成单 Agent 草案。"],
    }


def _available_tool_context() -> str:
    rows: list[str] = []
    for server in _mcp_servers.values():
        if server.status != "installed" or not server.enabled:
            continue
        for tool in server.tools:
            rows.append(f"- id={tool.id}; name={tool.name}; description={tool.description}")
    return "\n".join(rows[:80])


def _available_skill_context() -> str:
    rows: list[str] = []
    for skill in _skills.values():
        if not skill.enabled:
            continue
        rows.append(
            f"- id={skill.id}; name={skill.name}; category={skill.category}; "
            f"description={skill.description}; trigger={skill.trigger}"
        )
    return "\n".join(rows[:80])


def _resolve_tools(names: list[str]) -> tuple[list[BuilderRecommendedItem], list[str]]:
    matched: list[BuilderRecommendedItem] = []
    missing: list[str] = []
    tools = [
        tool
        for server in _mcp_servers.values()
        if server.status == "installed" and server.enabled
        for tool in server.tools
    ]
    for name in names:
        found = _best_match(name, [(tool.id, tool.name, tool.description) for tool in tools])
        if found:
            matched.append(BuilderRecommendedItem(
                id=found[0],
                name=found[1],
                reason=f"匹配需求能力: {name}",
                matched=True,
            ))
        else:
            missing.append(name)
    return matched, missing


def _resolve_skills(names: list[str]) -> tuple[list[BuilderRecommendedItem], list[str]]:
    matched: list[BuilderRecommendedItem] = []
    missing: list[str] = []
    skills = [skill for skill in _skills.values() if skill.enabled]
    for name in names:
        found = _best_match(
            name,
            [
                (skill.id, skill.name, " ".join([skill.description, skill.trigger, " ".join(skill.tags)]))
                for skill in skills
            ],
        )
        if found:
            matched.append(BuilderRecommendedItem(
                id=found[0],
                name=found[1],
                reason=f"匹配需求能力: {name}",
                matched=True,
            ))
        else:
            missing.append(name)
    return matched, missing


def _best_match(query: str, candidates: list[tuple[str, str, str]]) -> tuple[str, str, str] | None:
    needle = query.strip().lower()
    if not needle:
        return None
    for candidate in candidates:
        haystack = " ".join(candidate).lower()
        if needle in haystack or any(part and part in haystack for part in re.split(r"[\s,_/-]+", needle)):
            return candidate
    return None


def _guess_tool_names(requirement: str) -> list[str]:
    text = requirement.lower()
    guesses: list[str] = []
    if any(word in text for word in ["搜索", "互联网", "web", "网页", "资料"]):
        guesses.append("web search")
    if any(word in text for word in ["代码", "项目", "文件", "实现", "修复"]):
        guesses.extend(["filesystem", "code search"])
    if any(word in text for word in ["数据库", "sql", "sqlite"]):
        guesses.append("database")
    return _unique_nonempty(guesses)


def _guess_skill_names(requirement: str) -> list[str]:
    text = requirement.lower()
    guesses: list[str] = []
    if any(word in text for word in ["需求", "prd", "产品"]):
        guesses.append("prd writing")
    if any(word in text for word in ["架构", "方案", "设计"]):
        guesses.append("architecture design")
    if any(word in text for word in ["测试", "验证", "review", "评审"]):
        guesses.append("test review")
    return _unique_nonempty(guesses)


def _parse_json_object(text: str) -> dict:
    stripped = text.strip()
    if stripped.startswith("```"):
        stripped = re.sub(r"^```(?:json)?", "", stripped).strip()
        stripped = re.sub(r"```$", "", stripped).strip()
    try:
        parsed = json.loads(stripped)
    except json.JSONDecodeError:
        match = re.search(r"\{.*\}", stripped, re.S)
        if not match:
            raise ValueError("模型没有返回 JSON 对象")
        parsed = json.loads(match.group(0))
    if not isinstance(parsed, dict):
        raise ValueError("模型返回 JSON 顶层必须是对象")
    return parsed


def _as_string_list(value: object) -> list[str]:
    if not isinstance(value, list):
        return []
    return [str(item).strip() for item in value if str(item).strip()]


def _unique_nonempty(items: list[str]) -> list[str]:
    seen: set[str] = set()
    result: list[str] = []
    for item in items:
        value = str(item).strip()
        key = value.lower()
        if value and key not in seen:
            seen.add(key)
            result.append(value)
    return result


def _make_title(requirement: str, fallback: str) -> str:
    compact = " ".join(requirement.strip().split())
    if not compact:
        return fallback
    title = compact[:24]
    if len(compact) <= 24 and not title.endswith(("Agent", "agent")):
        title += " Agent"
    return title


def _default_agent_prompt(name: str, description: str) -> str:
    return "\n".join([
        f"You are {name}.",
        description or "Work carefully according to your assigned responsibility.",
        "Use bound MCP tools and Skills when they are relevant.",
        "When you are ready to answer the user, call FinalAnswerStart exactly once before writing the final answer.",
    ])
